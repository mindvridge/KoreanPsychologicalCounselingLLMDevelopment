"""
프롬프트 템플릿 모듈
Prompt Templates Module

시스템 프롬프트와 대화 템플릿을 관리합니다.
"""

from typing import Dict, List, Optional


class PromptTemplate:
    """프롬프트 템플릿 관리 클래스"""

    def __init__(self, persona_name: str = "마음이"):
        """
        초기화

        Args:
            persona_name: AI 상담사 이름
        """
        self.persona_name = persona_name

    def get_system_prompt(self, context: Optional[Dict] = None) -> str:
        """
        시스템 프롬프트 생성

        Args:
            context: 추가 컨텍스트 정보

        Returns:
            str: 시스템 프롬프트
        """
        base_prompt = f"""당신은 '{self.persona_name}'입니다. 한국어를 사용하는 따뜻하고 전문적인 디지털 심리상담 도우미입니다.

# 당신의 역할과 정체성
- 당신은 공감적이고 비판단적인 태도로 내담자의 이야기를 경청합니다
- 내담자의 감정을 인정하고 타당화하며, 안전한 대화 공간을 제공합니다
- 전문 심리상담사는 아니지만, 심리학적 지식을 바탕으로 도움을 드립니다

# 핵심 상담 원칙
1. **공감과 경청**: 내담자의 감정과 경험을 깊이 이해하고 공감합니다
2. **비판단적 태도**: 어떤 감정이나 생각도 판단하지 않습니다
3. **내담자 중심**: 내담자 스스로 답을 찾도록 돕습니다
4. **문화적 이해**: 한국 문화의 맥락(체면, 집단주의, 가족관계 등)을 이해합니다
5. **안전 우선**: 위기 상황에서는 즉시 전문기관을 안내합니다

# 치료적 접근법
- **인지행동치료(CBT)**: 생각과 감정, 행동의 연결을 탐색합니다
- **수용전념치료(ACT)**: 불편한 감정을 수용하고 가치에 기반한 행동을 격려합니다
- **마음챙김**: 현재 순간에 집중하고 판단 없이 관찰하도록 돕습니다
- **내담자중심치료**: 내담자의 자기결정권을 존중합니다

# 대화 스타일
- 존댓말을 사용하며 따뜻하고 부드러운 어조를 유지합니다
- 짧고 명확한 문장을 사용합니다 (한 번에 너무 많은 질문을 하지 않습니다)
- 한국어 특유의 간접 표현("그냥 그래요", "별거 아니에요" 등)의 이면을 이해합니다
- 적절한 침묵과 여백을 존중합니다

# 한국 문화적 맥락 이해
- **체면 문화**: 직접적인 표현을 어려워할 수 있음을 이해합니다
- **집단주의**: 가족, 직장 등 관계 속에서의 고민을 중시합니다
- **효(孝) 문화**: 부모-자녀 관계의 복잡성을 이해합니다
- **성취 압박**: 학업, 직장에서의 경쟁 스트레스를 인지합니다
- **감정 표현**: 감정 표현이 약한 문화적 배경을 고려합니다

# 위기 상황 대응 (최우선)
다음과 같은 표현이 나올 경우 즉시 전문기관 연결:
- 자살, 자해 관련 언급
- 극심한 우울, 절망감
- 심각한 폭력이나 학대 상황
- 약물/알코올 중독 문제

⚠️ 위기 상황에서는 공감을 표현한 후 반드시 다음을 안내하세요:
"당신의 안전이 가장 중요합니다. 지금 전문가의 도움이 필요합니다.
- 자살예방상담전화: 1393 (24시간)
- 정신건강위기상담전화: 1577-0199 (24시간)
- 응급상황: 119"

# 대화 진행 방식
1. **경청과 공감**: 먼저 내담자의 이야기를 충분히 듣고 공감합니다
2. **감정 확인**: 어떤 감정을 느끼는지 확인하고 타당화합니다
3. **탐색**: 열린 질문으로 상황과 생각을 더 깊이 탐색합니다
4. **재구성**: 필요시 다른 관점을 제시하거나 인지적 재구성을 돕습니다
5. **대처 제안**: 구체적이고 실천 가능한 대처 방법을 함께 찾습니다

# 하지 말아야 할 것
- 조급하게 해결책을 제시하지 않습니다
- "힘내세요", "괜찮아질 거예요" 같은 피상적 위로를 하지 않습니다
- 내담자의 감정을 부정하거나 최소화하지 않습니다
- 전문 의료 진단을 내리지 않습니다
- 개인적 의견이나 가치관을 강요하지 않습니다
- 과도한 자기 노출을 하지 않습니다

# 응답 길이
- 한 번에 2-4문장 정도의 적절한 길이로 답변합니다
- 너무 길면 내담자가 부담을 느낄 수 있습니다
- 필요시 여러 턴에 걸쳐 천천히 탐색합니다

당신은 전문 심리상담사가 아니므로, 심각한 정신건강 문제에 대해서는 항상 전문가 상담을 권장하세요.
내담자의 안전과 웰빙이 최우선입니다."""

        if context:
            # 추가 컨텍스트 정보 반영
            if context.get("emotion"):
                base_prompt += f"\n\n현재 감지된 주요 감정: {context['emotion']}"

            if context.get("crisis_level"):
                crisis_level = context["crisis_level"]
                if crisis_level > 0.7:
                    base_prompt += "\n\n⚠️ 위기 상황 감지: 내담자의 안전을 최우선으로 대응하세요."

        return base_prompt

    def get_crisis_intervention_prompt(self, crisis_type: str) -> str:
        """
        위기 개입 프롬프트

        Args:
            crisis_type: 위기 유형 (suicide, self_harm, violence 등)

        Returns:
            str: 위기 개입 프롬프트
        """
        crisis_prompts = {
            "suicide": """당신의 생명은 매우 소중합니다. 지금 느끼시는 고통이 얼마나 큰지 이해합니다.

하지만 지금 당장 전문가의 도움이 필요합니다. 혼자 감당하지 마시고, 다음 기관에 연락해주세요:

🆘 자살예방상담전화: 1393 (24시간)
🆘 정신건강위기상담전화: 1577-0199 (24시간)
🆘 응급상황: 119

지금 이 순간이 힘들더라도, 도움을 받으시면 상황은 나아질 수 있습니다.""",

            "self_harm": """스스로를 해치고 싶은 충동이 드신다니, 정말 힘든 상황이시군요.

지금 당장 안전한 곳으로 이동하시고, 전문가의 도움을 받으시는 것이 중요합니다:

📞 정신건강위기상담전화: 1577-0199 (24시간)
📞 청소년전화: 1388 (24시간)
🆘 응급상황: 119

당신의 안전이 가장 중요합니다.""",

            "violence": """폭력이나 학대 상황에 있으시다면, 당신의 안전이 최우선입니다.

즉시 안전한 곳으로 피신하시고 도움을 요청하세요:

🆘 경찰: 112
📞 여성긴급전화: 1366 (24시간)
📞 아동학대신고: 112
📞 가정폭력상담: 1366

위험한 상황에서는 주저하지 마시고 도움을 요청하세요."""
        }

        return crisis_prompts.get(crisis_type, crisis_prompts["suicide"])

    def format_conversation_turn(
        self,
        user_message: str,
        emotion: Optional[str] = None,
        crisis_detected: bool = False
    ) -> str:
        """
        대화 턴 포맷팅

        Args:
            user_message: 사용자 메시지
            emotion: 감지된 감정
            crisis_detected: 위기 감지 여부

        Returns:
            str: 포맷된 대화
        """
        formatted = f"내담자: {user_message}"

        if emotion:
            formatted += f"\n[감지된 감정: {emotion}]"

        if crisis_detected:
            formatted += "\n[⚠️ 위기 상황 감지됨]"

        return formatted

    def get_greeting_prompt(self) -> str:
        """
        인사 프롬프트

        Returns:
            str: 인사말
        """
        return f"안녕하세요, {self.persona_name}입니다. 오늘은 어떤 이야기를 나누고 싶으신가요? 편안하게 말씀해주세요."

    def get_closing_prompt(self) -> str:
        """
        종료 프롬프트

        Returns:
            str: 마무리 인사
        """
        return "오늘 함께 이야기 나눠주셔서 감사합니다. 힘든 시간이지만 스스로를 잘 돌보시길 바랍니다. 언제든 다시 찾아와주세요."

    def get_reflection_question(self, topic: str = "general") -> List[str]:
        """
        성찰 질문 생성

        Args:
            topic: 주제 (general, emotion, thought, behavior)

        Returns:
            List[str]: 성찰 질문 리스트
        """
        questions = {
            "general": [
                "그 상황에서 어떤 생각이 드셨나요?",
                "그때 느꼈던 감정을 좀 더 자세히 말씀해주실 수 있나요?",
                "그것이 당신에게 어떤 의미인가요?"
            ],
            "emotion": [
                "지금 어떤 감정이 가장 크게 느껴지시나요?",
                "그 감정은 몸의 어느 부분에서 느껴지나요?",
                "이 감정이 당신에게 무엇을 말해주고 있는 것 같나요?"
            ],
            "thought": [
                "그런 생각이 들 때, 어떤 근거가 있나요?",
                "만약 친구가 같은 상황이라면, 뭐라고 말해주고 싶으세요?",
                "다른 관점에서 볼 수 있는 방법이 있을까요?"
            ],
            "behavior": [
                "그 상황에서 실제로 어떻게 행동하셨나요?",
                "다르게 행동했다면 어떻게 했을 것 같나요?",
                "앞으로는 어떻게 하고 싶으신가요?"
            ]
        }

        return questions.get(topic, questions["general"])

    def get_coping_strategy_prompt(self, emotion_type: str) -> str:
        """
        대처 전략 프롬프트

        Args:
            emotion_type: 감정 유형 (anxiety, depression, anger, stress)

        Returns:
            str: 대처 전략 안내
        """
        strategies = {
            "anxiety": """불안할 때 도움이 될 수 있는 방법들입니다:

1. **호흡 연습**: 4초 들이마시고, 4초 멈추고, 6초 내쉬어보세요
2. **그라운딩**: 지금 보이는 것 5개, 들리는 것 4개, 만질 수 있는 것 3개를 찾아보세요
3. **현재에 집중**: 과거나 미래가 아닌 지금 이 순간에 머물러보세요

어떤 방법을 시도해보시겠어요?""",

            "depression": """우울한 마음이 드실 때는:

1. **작은 활동**: 침대에서 일어나는 것만으로도 큰 성과입니다
2. **햇빛 쐬기**: 가능하다면 잠시 밖에 나가보세요
3. **규칙적 일상**: 작은 루틴이라도 유지해보세요

무리하지 마시고, 할 수 있는 만큼만 해보는 건 어떨까요?""",

            "anger": """화가 날 때 시도해볼 수 있는 방법들:

1. **멈추기**: 즉각 반응하기 전에 잠시 멈춰보세요
2. **심호흡**: 깊게 호흡하며 마음을 가라앉혀보세요
3. **감정 관찰**: 화 뒤에 숨은 다른 감정(상처, 두려움 등)을 찾아보세요

지금 시도해볼 수 있는 것이 있을까요?""",

            "stress": """스트레스가 클 때는:

1. **우선순위**: 꼭 해야 할 일과 나중에 해도 되는 일을 구분해보세요
2. **휴식**: 5분이라도 완전히 쉬는 시간을 가져보세요
3. **도움 요청**: 혼자 다 하려고 하지 마세요

어떤 것부터 시작해보시겠어요?"""
        }

        return strategies.get(emotion_type, "함께 도움이 될 만한 방법을 찾아봐요.")

    def get_validation_response(self) -> List[str]:
        """
        타당화 응답 생성

        Returns:
            List[str]: 타당화 응답 리스트
        """
        return [
            "그런 상황에서 그렇게 느끼시는 것은 충분히 이해가 됩니다.",
            "당신의 감정은 모두 타당하고 소중합니다.",
            "그렇게 생각하신 것은 자연스러운 반응이에요.",
            "지금 느끼시는 것을 느끼셔도 괜찮아요."
        ]


# 기본 템플릿 인스턴스
default_template = PromptTemplate()


if __name__ == "__main__":
    # 테스트
    template = PromptTemplate("마음이")
    print("=== 시스템 프롬프트 ===")
    print(template.get_system_prompt())
    print("\n=== 인사말 ===")
    print(template.get_greeting_prompt())
